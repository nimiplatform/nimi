#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const APP_TOOLS_ROOT = path.resolve(SCRIPT_DIR, '..');
const AUTHORITY_PATH = path.resolve(
  APP_TOOLS_ROOT,
  '../.nimi/spec/platform/kernel/tables/simulator-browser-effects.yaml',
);
const OUTPUT_PATH = path.resolve(APP_TOOLS_ROOT, 'lib/simulator-effect-policy.generated.mjs');
const AUTHORITY_LABEL = '.nimi/spec/platform/kernel/tables/simulator-browser-effects.yaml';
const CLASSIFICATIONS = new Set(['forbidden', 'port_only', 'pure_read']);

function sha256(bytes) {
  return `sha256:${createHash('sha256').update(bytes).digest('hex')}`;
}

function stringArray(value, field) {
  if (!Array.isArray(value) || value.length === 0
    || value.some((entry) => typeof entry !== 'string' || !entry)) {
    throw new Error(`${field} must be a non-empty string array`);
  }
  return [...value];
}

function projectAuthority(bytes) {
  const document = YAML.parseDocument(bytes.toString('utf8'), {
    merge: false,
    uniqueKeys: true,
  });
  if (document.errors.length > 0) {
    throw new Error(document.errors.map((entry) => entry.message).join('; '));
  }
  const authority = document.toJS({ maxAliasCount: 0 });
  if (authority?.protocol_id !== 'platform_simulator_browser_effects'
    || authority?.source_rule !== 'P-SIM-018'
    || !Array.isArray(authority.entries)) {
    throw new Error('unexpected Simulator browser-effect authority identity or entries');
  }
  const ids = new Set();
  const entries = authority.entries.map((entry, index) => {
    const field = `entries[${index}]`;
    if (!entry || typeof entry !== 'object'
      || typeof entry.id !== 'string' || !entry.id
      || typeof entry.browser_surface !== 'string' || !entry.browser_surface
      || !CLASSIFICATIONS.has(entry.classification)) {
      throw new Error(`${field} has an invalid id, browser_surface, or classification`);
    }
    if (ids.has(entry.id)) throw new Error(`${field}.id is duplicated`);
    ids.add(entry.id);
    const surfaces = entry.browser_surface.split('|');
    if (surfaces.some((surface) => !surface || surface !== surface.trim())) {
      throw new Error(`${field}.browser_surface must contain exact non-empty targets`);
    }
    const permittedOwners = entry.permitted_owners
      ?? (entry.permitted_owner ? [entry.permitted_owner] : []);
    if (!Array.isArray(permittedOwners)
      || permittedOwners.some((owner) => typeof owner !== 'string' || !owner)) {
      throw new Error(`${field}.permitted_owner(s) must be strings`);
    }
    return {
      id: entry.id,
      classification: entry.classification,
      surfaces,
      governedOwners: stringArray(entry.governed_owners, `${field}.governed_owners`),
      permittedOwners: [...permittedOwners],
      phases: stringArray(entry.phases, `${field}.phases`),
    };
  });
  return {
    authority: {
      path: AUTHORITY_LABEL,
      digest: sha256(bytes),
      protocolId: authority.protocol_id,
      sourceRule: authority.source_rule,
    },
    entries,
  };
}

function renderProjection(projection) {
  const entryLines = projection.entries
    .map((entry) => `    ${JSON.stringify(entry)}`)
    .join(',\n');
  return `// Generated by scripts/generate-simulator-effect-policy.mjs. Do not edit.\n`
    + `function deepFreeze(value) {\n`
    + `  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;\n`
    + `  for (const child of Object.values(value)) deepFreeze(child);\n`
    + `  return Object.freeze(value);\n`
    + `}\n\n`
    + `export const SIMULATOR_EFFECT_POLICY = deepFreeze({\n`
    + `  authority: ${JSON.stringify(projection.authority)},\n`
    + `  entries: [\n${entryLines}\n  ],\n`
    + `});\n`;
}

export function expectedSimulatorEffectPolicyProjection() {
  const bytes = readFileSync(AUTHORITY_PATH);
  return renderProjection(projectAuthority(bytes));
}

function main(args) {
  const mode = args[0];
  if (!['--apply', '--check', '--print'].includes(mode) || args.length !== 1) {
    throw new Error('usage: generate-simulator-effect-policy.mjs --apply|--check|--print');
  }
  const expected = expectedSimulatorEffectPolicyProjection();
  if (mode === '--print') {
    process.stdout.write(expected);
    return;
  }
  if (mode === '--apply') {
    writeFileSync(OUTPUT_PATH, expected);
    process.stdout.write('[simulator-effect-policy] projection updated\n');
    return;
  }
  let actual = '';
  try {
    actual = readFileSync(OUTPUT_PATH, 'utf8');
  } catch {
    // Missing output is reported as deterministic drift below.
  }
  if (actual !== expected) {
    throw new Error(`Simulator effect policy projection drift: run ${path.relative(process.cwd(), fileURLToPath(import.meta.url))} --apply`);
  }
  process.stdout.write('[simulator-effect-policy] projection check passed\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(1);
  }
}
