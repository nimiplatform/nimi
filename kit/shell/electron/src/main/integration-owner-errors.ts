export function isIntegrationOwnerReasonMetadata(reasonCode: string, value: unknown): value is string {
  return ['LOCAL_APP_OPERATION_UNAVAILABLE', 'LOCAL_APP_OWNER_UNAVAILABLE',
    'local-app-operation-unavailable', 'local-app-owner-unavailable'].includes(reasonCode)
    && typeof value === 'string' && INTEGRATION_OWNER_ERROR_REASONS.has(value);
}
