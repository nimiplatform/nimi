import path from 'node:path';

import { generatedBy, readYaml, writeText } from './context.mjs';

const AUTH_POSTURE_INDEX = 'config/runtime-rpc-auth-posture.yaml';
const AUTH_POSTURE_DIR = 'config/runtime-rpc-auth-posture';
export function writeTypescriptRuntimeAuthPostureProjection(runtime) {
  const index = readYaml(AUTH_POSTURE_INDEX);
  const rows = [];
  for (const shard of index.method_shards ?? []) {
    const shardPath = path.join(AUTH_POSTURE_DIR, path.basename(String(shard.path || '')));
    const document = readYaml(shardPath);
    for (const method of document.methods ?? []) {
      const methodId = String(method.method_id || '').trim();
      const posture = String(method.posture || '').trim();
      if (!methodId || !posture) {
        throw new Error(`invalid Runtime RPC auth posture row in ${shardPath}`);
      }
      rows.push({ methodId, posture });
    }
  }
  const methodIds = new Set(runtime.method_ids);
  const duplicateIds = rows.filter((row, index) => rows.findIndex((candidate) => candidate.methodId === row.methodId) !== index);
  const unknownIds = rows.filter((row) => !methodIds.has(row.methodId));
  if (duplicateIds.length || unknownIds.length) {
    throw new Error(`Runtime RPC auth posture projection mismatch: duplicates=${duplicateIds.length} unknown=${unknownIds.length}`);
  }
  rows.sort((left, right) => left.methodId.localeCompare(right.methodId));
  const postureType = [...new Set(rows.map((row) => row.posture))]
    .sort()
    .map((posture) => JSON.stringify(posture))
    .join(' | ');
  const entries = rows
    .map(({ methodId, posture }) => `  ${JSON.stringify(methodId)}: ${JSON.stringify(posture)},`)
    .join('\n');
  writeText('sdks/typescript/core-generated/runtime-rpc-auth-posture.ts', `// @generated by ${generatedBy}
// Source: ${AUTH_POSTURE_INDEX} and its admitted method shards.

export type RuntimeRpcAuthPosture = ${postureType};

const RUNTIME_RPC_AUTH_POSTURES: Readonly<Record<string, RuntimeRpcAuthPosture>> = {
${entries}
};

export function runtimeRpcAuthPosture(methodId: string): RuntimeRpcAuthPosture | null {
  return RUNTIME_RPC_AUTH_POSTURES[methodId] ?? null;
}
`);
}
