#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const sourceRelative = '.nimi/spec/runtime/kernel/tables/bundled-avatar-runtime-profile.yaml';
const sourcePath = path.join(repoRoot, sourceRelative);
const profile = YAML.parse(fs.readFileSync(sourcePath, 'utf8'));

if (profile?.profile_id !== 'bundled_avatar_v1' || profile?.app_id !== 'nimi.avatar') {
  throw new Error('Bundled Avatar profile identity is invalid');
}
const profileMarker = String(profile?.native_profile_marker || '').trim();
const accountCaller = profile?.account_caller;
const appInstanceId = String(accountCaller?.app_instance_id || '').trim();
const deviceId = String(accountCaller?.device_id || '').trim();
const realmOperations = Array.isArray(profile?.realm_operations)
  ? profile.realm_operations.map((value) => String(value || '').trim())
  : [];
if (profileMarker !== 'avatar-v1' || appInstanceId !== 'nimi.avatar.desktop-supervised'
  || deviceId !== 'desktop-avatar-host' || realmOperations.length === 0
  || realmOperations.some((value) => !value)) {
  throw new Error('Bundled Avatar fixed host identity is invalid');
}
if (!Array.isArray(profile.methods) || profile.methods.length === 0) {
  throw new Error('Bundled Avatar profile requires methods');
}

const seen = new Set();
const methods = profile.methods.map((entry) => {
  const methodId = String(entry?.method_id || '').trim();
  const kind = String(entry?.kind || '').trim();
  const capability = String(entry?.capability || '').trim();
  if (!/^\/nimi\.runtime\.v1\.[A-Za-z0-9]+\/[A-Za-z0-9]+$/u.test(methodId)) {
    throw new Error(`Invalid bundled Avatar method id: ${methodId}`);
  }
  if (kind !== 'unary' && kind !== 'server_stream') {
    throw new Error(`Invalid bundled Avatar method kind for ${methodId}: ${kind}`);
  }
  if (!capability || capability !== capability.trim()) {
    throw new Error(`Invalid bundled Avatar capability for ${methodId}`);
  }
  if (seen.has(methodId)) {
    throw new Error(`Duplicate bundled Avatar method: ${methodId}`);
  }
  seen.add(methodId);
  const match = /^\/nimi\.runtime\.v1\.([A-Za-z0-9]+)\/([A-Za-z0-9]+)$/u.exec(methodId);
  const service = match?.[1] || '';
  const rpc = match?.[2] || '';
  const methodName = `${rpc.slice(0, 1).toLowerCase()}${rpc.slice(1)}`;
  return { methodId, kind, capability, service, methodName };
});

const outputs = new Map([
  ['runtime/internal/bundledavatar/profile_generated.go', renderGo(methods, realmOperations)],
  ['kit/shell/protected-local/src/bundled_avatar_profile_generated.rs', renderRust(methods)],
  ['kit/shell/electron/src/main/bundled-avatar-profile.generated.ts', renderTypeScript(methods)],
  ['sdks/typescript/runtime/bundled-avatar-profile.generated.ts', renderSdkIdentityTypeScript(methods)],
]);

let drift = false;
for (const [relativePath, content] of outputs) {
  const outputPath = path.join(repoRoot, relativePath);
  if (checkOnly) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
    if (current !== content) {
      process.stderr.write(`bundled Avatar profile drift: ${relativePath}\n`);
      drift = true;
    }
    continue;
  }
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, content, 'utf8');
}
if (drift) process.exit(1);
process.stdout.write(`${checkOnly ? 'checked' : 'generated'} bundled_avatar_v1 (${methods.length} methods)\n`);

function renderGo(entries, admittedRealmOperations) {
  const cases = entries.map((entry) => `\tcase ${JSON.stringify(entry.methodId)}:\n\t\treturn MethodProfile{Kind: ${entry.kind === 'unary' ? 'MethodUnary' : 'MethodServerStream'}, Capability: ${JSON.stringify(entry.capability)}}, true`).join('\n');
  const realmCases = admittedRealmOperations.map((operation) => `\tcase ${JSON.stringify(operation)}:\n\t\treturn true`).join('\n');
  const source = `// Code generated by scripts/generate-bundled-avatar-runtime-profile.mjs; DO NOT EDIT.\n// Source: ${sourceRelative}\n\npackage bundledavatar\n\nconst (\n\tProfileID = "bundled_avatar_v1"\n\tAppID = "nimi.avatar"\n\tNativeProfileMarker = ${JSON.stringify(profileMarker)}\n\tAppInstanceID = ${JSON.stringify(appInstanceId)}\n\tDeviceID = ${JSON.stringify(deviceId)}\n)\n\ntype MethodKind string\n\nconst (\n\tMethodUnary MethodKind = "unary"\n\tMethodServerStream MethodKind = "server_stream"\n)\n\ntype MethodProfile struct {\n\tKind MethodKind\n\tCapability string\n}\n\nfunc Method(methodID string) (MethodProfile, bool) {\n\tswitch methodID {\n${cases}\n\tdefault:\n\t\treturn MethodProfile{}, false\n\t}\n}\n\nfunc RealmOperationAllowed(operationID string) bool {\n\tswitch operationID {\n${realmCases}\n\tdefault:\n\t\treturn false\n\t}\n}\n`;
  return execFileSync('gofmt', { input: source, encoding: 'utf8' });
}

function renderRust(entries) {
  const cases = entries.map((entry) => `        ${JSON.stringify(entry.methodId)} => Some(BundledAvatarMethodProfile {\n            method_id: ${JSON.stringify(entry.methodId)},\n            kind: BundledAvatarMethodKind::${entry.kind === 'unary' ? 'Unary' : 'ServerStream'},\n            capability: ${JSON.stringify(entry.capability)},\n        }),`).join('\n');
  return `// Code generated by scripts/generate-bundled-avatar-runtime-profile.mjs; DO NOT EDIT.\n// Source: ${sourceRelative}\n\npub const BUNDLED_AVATAR_APP_ID: &str = "nimi.avatar";\npub const BUNDLED_AVATAR_NATIVE_PROFILE_MARKER: &str = ${JSON.stringify(profileMarker)};\n\n#[derive(Clone, Copy, Debug, Eq, PartialEq)]\npub enum BundledAvatarMethodKind {\n    Unary,\n    ServerStream,\n}\n\n#[derive(Clone, Copy, Debug, Eq, PartialEq)]\npub struct BundledAvatarMethodProfile {\n    pub method_id: &'static str,\n    pub kind: BundledAvatarMethodKind,\n    pub capability: &'static str,\n}\n\npub fn bundled_avatar_method_profile(method_id: &str) -> Option<BundledAvatarMethodProfile> {\n    match method_id {\n${cases}\n        _ => None,\n    }\n}\n`;
}

function renderTypeScript(entries) {
  const records = entries.map((entry) => `  ${JSON.stringify(entry.methodId)}: { kind: ${JSON.stringify(entry.kind)}, capability: ${JSON.stringify(entry.capability)} },`).join('\n');
  return `// Code generated by scripts/generate-bundled-avatar-runtime-profile.mjs; DO NOT EDIT.\n// Source: ${sourceRelative}\n\nexport const NIMI_ELECTRON_BUNDLED_AVATAR_PROFILE_ID = 'bundled_avatar_v1' as const;\nexport const NIMI_ELECTRON_BUNDLED_AVATAR_APP_ID = 'nimi.avatar' as const;\nexport const NIMI_ELECTRON_BUNDLED_AVATAR_APP_INSTANCE_ID = ${JSON.stringify(appInstanceId)} as const;\nexport const NIMI_ELECTRON_BUNDLED_AVATAR_DEVICE_ID = ${JSON.stringify(deviceId)} as const;\n\nexport const NIMI_ELECTRON_BUNDLED_AVATAR_METHODS = {\n${records}\n} as const;\n\nexport type NimiElectronBundledAvatarMethodId = keyof typeof NIMI_ELECTRON_BUNDLED_AVATAR_METHODS;\n\nexport function isNimiElectronBundledAvatarUnaryMethod(methodId: string): methodId is NimiElectronBundledAvatarMethodId {\n  return NIMI_ELECTRON_BUNDLED_AVATAR_METHODS[methodId as NimiElectronBundledAvatarMethodId]?.kind === 'unary';\n}\n\nexport function isNimiElectronBundledAvatarServerStreamMethod(methodId: string): methodId is NimiElectronBundledAvatarMethodId {\n  return NIMI_ELECTRON_BUNDLED_AVATAR_METHODS[methodId as NimiElectronBundledAvatarMethodId]?.kind === 'server_stream';\n}\n`;
}

function renderSdkIdentityTypeScript(entries) {
  const groupByService = new Map([
    ['RuntimeAuditService', 'audit'],
    ['RuntimeAccountService', 'account'],
    ['RuntimeAgentService', 'agents'],
    ['RuntimeArtifactService', 'artifacts'],
    ['RuntimeAiService', 'ai'],
    ['RuntimeAppService', 'appMessages'],
  ]);
  const groups = new Map();
  for (const entry of entries) {
    const group = groupByService.get(entry.service);
    if (!group) {
      throw new Error(`Bundled Avatar SDK method service is not mapped: ${entry.service}`);
    }
    const names = groups.get(group) || [];
    names.push(entry.methodName);
    groups.set(group, names);
  }
  const renderedGroups = [...groups.entries()]
    .map(([group, names]) => `  ${group}: ${JSON.stringify(names)},`)
    .join('\n');
  return `// Code generated by scripts/generate-bundled-avatar-runtime-profile.mjs; DO NOT EDIT.\n// Source: ${sourceRelative}\n\nimport type { RuntimeTypedClient } from '../core-generated/runtime-typed-client';\n\nexport const NIMI_BUNDLED_AVATAR_APP_ID = 'nimi.avatar' as const;\nexport const NIMI_BUNDLED_AVATAR_APP_INSTANCE_ID = ${JSON.stringify(appInstanceId)} as const;\nexport const NIMI_BUNDLED_AVATAR_DEVICE_ID = ${JSON.stringify(deviceId)} as const;\n\nexport const NIMI_BUNDLED_AVATAR_TYPED_METHOD_GROUPS = {\n${renderedGroups}\n} as const satisfies Readonly<Record<string, readonly (keyof RuntimeTypedClient)[]>>;\n\nexport type NimiBundledAvatarTypedMethodName = typeof NIMI_BUNDLED_AVATAR_TYPED_METHOD_GROUPS[keyof typeof NIMI_BUNDLED_AVATAR_TYPED_METHOD_GROUPS][number];\n`;
}
