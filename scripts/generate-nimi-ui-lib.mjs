#!/usr/bin/env node

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const tablesDir = path.join(repoRoot, 'config');
const outDir = path.join(repoRoot, 'kit', 'ui', 'src', 'generated');
const themesDir = path.join(outDir, 'themes');

async function readYaml(fileName) {
  const raw = await fs.readFile(path.join(tablesDir, `platform-${fileName}`), 'utf8');
  return YAML.parse(raw);
}

function cssHeader(source) {
  return [
    '/* AUTO-GENERATED by scripts/generate-nimi-ui-lib.mjs. DO NOT EDIT. */',
    `/* Source: config/platform-${source} */`,
    '',
  ].join('\n');
}

function toJs(value) {
  return JSON.stringify(value, null, 2);
}

function normalizePacks(themesDoc) {
  return Array.isArray(themesDoc?.packs) ? themesDoc.packs : [];
}

function tokenRows(tokensDoc) {
  return Array.isArray(tokensDoc?.tokens) ? tokensDoc.tokens : [];
}

function packValueMap(pack) {
  const values = pack?.values && typeof pack.values === 'object' ? pack.values : {};
  return new Map(Object.entries(values).map(([k, v]) => [String(k), String(v)]));
}

function toKebab(role) {
  return role.replace(/_/gu, '-');
}

// ---------------------------------------------------------------------------
// tokens.ts — simplified: pack/scheme/accent IDs + types only
// ---------------------------------------------------------------------------

function renderTokensFile(tokensDoc, themesDoc) {
  const packs = normalizePacks(themesDoc);
  const tokens = tokenRows(tokensDoc);

  const typographyRoles = [];
  for (const token of tokens) {
    const match = String(token?.id || '').match(/^typography\.([a-z_]+)\.size$/u);
    if (match && !typographyRoles.includes(match[1])) {
      typographyRoles.push(match[1]);
    }
  }

  const foundationSchemeIds = packs.filter((p) => String(p?.pack_kind) === 'foundation').map((p) => String(p.theme_id));
  const accentPackIds = packs.filter((p) => String(p?.pack_kind) === 'accent').map((p) => String(p.theme_id));
  const densityPackIds = packs.filter((p) => String(p?.pack_kind) === 'density').map((p) => String(p.theme_id));
  const packIds = packs.map((p) => String(p.theme_id));

  return [
    '// AUTO-GENERATED by scripts/generate-nimi-ui-lib.mjs. DO NOT EDIT.',
    '// Source: config/platform-nimi-ui-tokens.yaml + config/platform-nimi-ui-themes.yaml',
    '',
    `export const DESIGN_PACK_IDS = ${toJs(packIds)} as const;`,
    `export const FOUNDATION_SCHEME_IDS = ${toJs(foundationSchemeIds)} as const;`,
    `export const ACCENT_PACK_IDS = ${toJs(accentPackIds)} as const;`,
    `export const DENSITY_PACK_IDS = ${toJs(densityPackIds)} as const;`,
    `export const TYPOGRAPHY_ROLE_IDS = ${toJs(typographyRoles)} as const;`,
    '',
    'export type GeneratedNimiDesignPackId = (typeof DESIGN_PACK_IDS)[number];',
    'export type GeneratedNimiFoundationSchemeId = (typeof FOUNDATION_SCHEME_IDS)[number];',
    'export type GeneratedNimiAccentPackId = (typeof ACCENT_PACK_IDS)[number];',
    'export type GeneratedNimiDensityPackId = (typeof DENSITY_PACK_IDS)[number];',
    'export type GeneratedNimiTypographyRoleId = (typeof TYPOGRAPHY_ROLE_IDS)[number];',
    '',
  ].join('\n');
}

// ---------------------------------------------------------------------------
// theme-base.css — @theme registration + @utility typography classes
// ---------------------------------------------------------------------------

function renderThemeBase(tokensDoc) {
  const tokens = tokenRows(tokensDoc);
  const blocks = [cssHeader('nimi-ui-tokens.yaml')];

  blocks.push('@layer nimi-theme.foundation, nimi-theme.accent;');
  blocks.push('');

  // Register all CSS vars with Tailwind 4 @theme so they become valid theme tokens.
  // Using `initial` as the value — actual values come from foundation/accent theme CSS.
  blocks.push('@theme {');
  for (const token of tokens) {
    const cssVar = String(token.css_var);
    blocks.push(`  ${cssVar}: initial;`);
  }
  blocks.push('}');
  blocks.push('');

  // Typography utility classes via @utility
  const roleSet = new Set();
  for (const token of tokens) {
    const match = String(token?.id || '').match(/^typography\.([a-z_]+)\.size$/u);
    if (match) roleSet.add(match[1]);
  }
  for (const role of [...roleSet].sort()) {
    const cssRole = toKebab(role);
    blocks.push(`@utility nimi-type-${cssRole} {`);
    blocks.push(`  font-size: var(--nimi-type-${cssRole}-size);`);
    blocks.push(`  line-height: var(--nimi-type-${cssRole}-line-height);`);
    blocks.push(`  font-weight: var(--nimi-type-${cssRole}-weight);`);
    blocks.push(`  letter-spacing: var(--nimi-type-${cssRole}-letter-spacing);`);
    if (role === 'mono') {
      blocks.push('  font-family: var(--nimi-font-mono);');
    }
    blocks.push('}');
    blocks.push('');
  }

  // Reduced motion
  blocks.push('@media (prefers-reduced-motion: reduce) {');
  blocks.push('  *, *::before, *::after {');
  blocks.push('    transition-duration: 0ms !important;');
  blocks.push('    animation-duration: 0ms !important;');
  blocks.push('  }');
  blocks.push('}');
  blocks.push('');

  return blocks.join('\n');
}

// ---------------------------------------------------------------------------
// Foundation theme CSS (light / dark)
// ---------------------------------------------------------------------------

function renderPackSelector(tokensDoc, pack, selector, onlyLayer = null, cascadeLayer = null) {
  const values = packValueMap(pack);
  const lines = [cssHeader('nimi-ui-themes.yaml')];
  if (cascadeLayer) {
    lines.push(`@layer ${cascadeLayer} {`);
  }
  lines.push(`${selector} {`);
  for (const token of tokenRows(tokensDoc)) {
    const themeLayer = String(token?.theme_layer || 'foundation');
    if (onlyLayer && themeLayer !== onlyLayer) continue;
    const id = String(token.id);
    const cssVar = String(token.css_var);
    const value = values.get(id);
    if (!value) continue;
    lines.push(`  ${cssVar}: ${value};`);
  }
  lines.push('}');
  if (cascadeLayer) {
    lines.push('}');
  }
  lines.push('');
  return lines.join('\n');
}

function renderFoundationTheme(tokensDoc, themesDoc, themeId, selector) {
  const pack = normalizePacks(themesDoc).find((item) => String(item?.theme_id) === themeId);
  if (!pack) throw new Error(`missing pack ${themeId}`);
  return renderPackSelector(tokensDoc, pack, selector, 'foundation', 'nimi-theme.foundation');
}

// ---------------------------------------------------------------------------
// Accent theme CSS
// ---------------------------------------------------------------------------

function renderAccentTheme(tokensDoc, themesDoc, themeId) {
  const pack = normalizePacks(themesDoc).find((item) => String(item?.theme_id) === themeId);
  if (!pack) throw new Error(`missing pack ${themeId}`);
  const selector = `:root[data-nimi-accent="${themeId}"], [data-nimi-accent="${themeId}"]`;
  return renderPackSelector(tokensDoc, pack, selector, 'accent', 'nimi-theme.accent');
}

// ---------------------------------------------------------------------------
// Density theme CSS (compact etc.)
// ---------------------------------------------------------------------------

function renderDensityTheme(tokensDoc, themesDoc, themeId) {
  const pack = normalizePacks(themesDoc).find((item) => String(item?.theme_id) === themeId);
  if (!pack) throw new Error(`missing pack ${themeId}`);
  const densityName = themeId.replace(/^nimi-density-/u, '');
  // Two-branch selector: the :root branch must out-specify the foundation
  // scheme selectors (`:root[data-nimi-scheme=...]` = 0,2,0) when density is
  // declared on <html>; the bare attribute branch covers subtree boundaries
  // (a direct rule always beats inherited values there).
  const selector = `:root[data-nimi-density="${densityName}"], [data-nimi-density="${densityName}"]`;
  // Density packs are value-driven overrides (sizing/typography only per
  // P-DESIGN-028); they live in the foundation cascade layer so import order
  // (foundation scheme -> density -> accent) resolves the override.
  const blocks = [renderPackSelector(tokensDoc, pack, selector, null, 'nimi-theme.foundation')];

  // Expressive escape hatch: an expressive boundary nested inside a compact
  // region restores the foundation values for every token the density pack
  // overrides. Sizing/typography values are scheme-independent, so the light
  // foundation pack is a safe source for the reset.
  const lightPack = normalizePacks(themesDoc).find((item) => String(item?.theme_id) === 'nimi-light');
  if (lightPack) {
    const densityValues = packValueMap(pack);
    const foundationValues = packValueMap(lightPack);
    const resetLines = [];
    for (const tokenId of densityValues.keys()) {
      const token = tokenRows(tokensDoc).find((row) => String(row?.id) === tokenId);
      const foundationValue = foundationValues.get(tokenId);
      if (!token || !foundationValue) continue;
      resetLines.push(`  ${String(token.css_var)}: ${foundationValue};`);
    }
    if (resetLines.length > 0) {
      blocks.push('@layer nimi-theme.foundation {');
      blocks.push(':root[data-nimi-density="expressive"], [data-nimi-density="expressive"] {');
      blocks.push(...resetLines);
      blocks.push('}');
      blocks.push('}');
      blocks.push('');
    }
  }
  return blocks.join('\n');
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------

async function main() {
  const checkMode = process.argv.includes('--check');
  const tokensDoc = await readYaml('nimi-ui-tokens.yaml');
  const themesDoc = await readYaml('nimi-ui-themes.yaml');
  const accentPackIds = normalizePacks(themesDoc)
    .filter((pack) => String(pack?.pack_kind) === 'accent')
    .map((pack) => String(pack.theme_id));
  const densityPackIds = normalizePacks(themesDoc)
    .filter((pack) => String(pack?.pack_kind) === 'density')
    .map((pack) => String(pack.theme_id));

  const renderedEntries = [
    [path.join(outDir, 'tokens.ts'), renderTokensFile(tokensDoc, themesDoc)],
    [path.join(outDir, 'theme-base.css'), renderThemeBase(tokensDoc)],
    [path.join(themesDir, 'light.css'), renderFoundationTheme(tokensDoc, themesDoc, 'nimi-light', ':root:not([data-nimi-scheme]), :root[data-nimi-scheme="light"], [data-nimi-scheme="light"]')],
    [path.join(themesDir, 'dark.css'), renderFoundationTheme(tokensDoc, themesDoc, 'nimi-dark', '.dark, :root[data-nimi-scheme="dark"], [data-nimi-scheme="dark"]')],
    ...accentPackIds.map((themeId) => [
      path.join(themesDir, `${themeId}.css`),
      renderAccentTheme(tokensDoc, themesDoc, themeId),
    ]),
    ...densityPackIds.map((themeId) => [
      path.join(themesDir, `${themeId}.css`),
      renderDensityTheme(tokensDoc, themesDoc, themeId),
    ]),
  ];
  const rendered = new Map(renderedEntries);

  if (checkMode) {
    const drifted = [];
    for (const [filePath, contents] of rendered) {
      let current = '';
      try {
        current = await fs.readFile(filePath, 'utf8');
      } catch {
        drifted.push(filePath);
        continue;
      }
      if (current !== contents) {
        drifted.push(filePath);
      }
    }
    if (drifted.length > 0) {
      process.stderr.write('nimi ui lib drift detected:\n');
      for (const item of drifted) {
        process.stderr.write(`  - ${path.relative(repoRoot, item)}\n`);
      }
      process.stderr.write('run `pnpm generate:nimi-ui-lib` to regenerate.\n');
      process.exitCode = 1;
      return;
    }
    process.stdout.write(`nimi ui lib is up-to-date (${rendered.size} files)\n`);
    return;
  }

  await fs.mkdir(themesDir, { recursive: true });
  for (const [filePath, contents] of rendered) {
    await fs.mkdir(path.dirname(filePath), { recursive: true });
    await fs.writeFile(filePath, contents, 'utf8');
  }
  process.stdout.write(`generated nimi ui lib projection (${rendered.size} files)\n`);
}

main().catch((error) => {
  process.stderr.write(`generate-nimi-ui-lib failed: ${String(error)}\n`);
  process.exitCode = 1;
});
