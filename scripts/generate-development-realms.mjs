import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const profiles = JSON.parse(readFileSync(path.join(root, 'config/development-realms.json'), 'utf8'));
const fields = ['apiOrigin', 'realtimeOrigin', 'webOrigin', 'environmentId'];
if (Object.keys(profiles).sort().join() !== 'local,official') throw new Error('Expected official and local Realm profiles.');
for (const [name, values] of Object.entries(profiles)) {
  if (Object.keys(values).sort().join() !== [...fields].sort().join()) throw new Error(`Invalid Realm profile: ${name}`);
  for (const field of fields.slice(0, 3)) {
    const url = new URL(values[field]);
    if (url.origin !== values[field] || url.username || url.password
      || (url.protocol !== 'https:' && !(name === 'local' && url.protocol === 'http:' && ['127.0.0.1', 'localhost'].includes(url.hostname)))) {
      throw new Error(`Invalid Realm origin: ${name}.${field}`);
    }
  }
  if (!/^[A-Za-z0-9][A-Za-z0-9_.-]{0,127}$/.test(values.environmentId)) throw new Error('Invalid Realm environment id.');
}
const js = '// Generated by scripts/generate-development-realms.mjs.\n'
  + 'export const REALM_PROFILES = Object.freeze({\n'
  + Object.entries(profiles).map(([name, values]) => `  ${name}: Object.freeze(${JSON.stringify(values)}),`).join('\n') + '\n});\n';
const go = '// Code generated by scripts/generate-development-realms.mjs; DO NOT EDIT.\n\npackage devenv\n\nimport "fmt"\n\n'
  + 'func ProfileFor(name string) (Profile, error) {\n\tswitch name {\n'
  + Object.entries(profiles).map(([name, values]) => `\tcase ${JSON.stringify(name)}:\n\t\treturn Profile{APIOrigin: ${JSON.stringify(values.apiOrigin)}, RealtimeOrigin: ${JSON.stringify(values.realtimeOrigin)}, WebOrigin: ${JSON.stringify(values.webOrigin)}, EnvironmentID: ${JSON.stringify(values.environmentId)}}, nil`).join('\n')
  + '\n\tdefault:\n\t\treturn Profile{}, fmt.Errorf("unknown development Realm: %s", name)\n\t}\n}\n';
for (const [relative, content] of [['app-tools/lib/realm-environments.generated.mjs', js], ['runtime/internal/devenv/profiles_generated.go', go]]) {
  const file = path.join(root, relative);
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== content) throw new Error(`Regenerate ${relative}`);
  } else {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
}
