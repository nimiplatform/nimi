#!/usr/bin/env node

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');

const header = `// Code generated by scripts/check-sdk-runtime-entrypoints.mjs. DO NOT EDIT.
// sdk-public-surface-snapshot: expand-local-reexports

`;

const browserSource = `${header}export * from './public-surface.js';
`;

const indexSource = `${header}export * from './public-surface.js';
export { createNodeGrpcTransport, setNodeGrpcBridge, type NodeGrpcBridge } from './transports/node-grpc.js';
`;

const files = [
  {
    path: path.join(repoRoot, 'sdk/src/runtime/browser.ts'),
    content: browserSource,
  },
  {
    path: path.join(repoRoot, 'sdk/src/runtime/index.ts'),
    content: indexSource,
  },
];

const publicSurfacePath = path.join(repoRoot, 'sdk/src/runtime/public-surface.ts');
const publicSurfaceGroupPrefix = '// sdk-runtime-public-surface-group: ';
const publicSurfaceGroups = [
  'core-contract',
  'local-runtime',
  'agent-surfaces',
  'route-scheduling',
  'ai-model-media-contracts',
  'connector-and-bridge-config',
  'agent-knowledge-memory-contracts',
  'audit-account-auth-contracts',
  'workflow-recommendation-assets',
  'runtime-client-codecs',
  'runtime-extension-modules',
];

function relative(filePath) {
  return path.relative(repoRoot, filePath).replaceAll(path.sep, '/');
}

function validatePublicSurfaceGroups(publicSurface, violations) {
  const allowedGroups = new Set(publicSurfaceGroups);
  const seenGroups = new Set();
  const exportCounts = new Map(publicSurfaceGroups.map((group) => [group, 0]));
  let currentGroup = null;
  let lastGroupIndex = -1;

  for (const [index, line] of publicSurface.split('\n').entries()) {
    const trimmed = line.trim();
    if (trimmed.startsWith(publicSurfaceGroupPrefix)) {
      const group = trimmed.slice(publicSurfaceGroupPrefix.length).trim();
      const groupIndex = publicSurfaceGroups.indexOf(group);
      if (!allowedGroups.has(group)) {
        violations.push(`sdk/src/runtime/public-surface.ts:${index + 1} unknown public surface group "${group}"`);
        currentGroup = null;
        continue;
      }
      if (seenGroups.has(group)) {
        violations.push(`sdk/src/runtime/public-surface.ts:${index + 1} repeats public surface group "${group}"`);
      }
      if (groupIndex <= lastGroupIndex) {
        violations.push(`sdk/src/runtime/public-surface.ts:${index + 1} public surface group "${group}" is out of canonical order`);
      }
      seenGroups.add(group);
      currentGroup = group;
      lastGroupIndex = groupIndex;
      continue;
    }

    if (trimmed.startsWith('export ')) {
      if (!currentGroup) {
        violations.push(`sdk/src/runtime/public-surface.ts:${index + 1} export is outside a public surface group`);
        continue;
      }
      exportCounts.set(currentGroup, (exportCounts.get(currentGroup) || 0) + 1);
    }
  }

  for (const group of publicSurfaceGroups) {
    if (!seenGroups.has(group)) {
      violations.push(`sdk/src/runtime/public-surface.ts missing public surface group "${group}"`);
      continue;
    }
    if ((exportCounts.get(group) || 0) === 0) {
      violations.push(`sdk/src/runtime/public-surface.ts public surface group "${group}" has no exports`);
    }
  }
}

async function main() {
  const write = process.argv.includes('--write');
  const violations = [];

  const publicSurface = await fs.readFile(publicSurfacePath, 'utf8');
  if (!publicSurface.includes('Shared authoritative export surface')) {
    violations.push('sdk/src/runtime/public-surface.ts missing shared surface authority header');
  }
  if (publicSurface.includes('node-grpc')) {
    violations.push('sdk/src/runtime/public-surface.ts must not export node-grpc transport symbols');
  }
  if (!publicSurface.includes('createTauriIpcTransport')) {
    violations.push('sdk/src/runtime/public-surface.ts must keep browser-safe Tauri transport export');
  }
  validatePublicSurfaceGroups(publicSurface, violations);

  for (const file of files) {
    if (write) {
      await fs.writeFile(file.path, file.content, 'utf8');
      continue;
    }

    const actual = await fs.readFile(file.path, 'utf8');
    if (actual !== file.content) {
      violations.push(`${relative(file.path)} drifted from generated wrapper; run pnpm generate:sdk-runtime-entrypoints`);
    }
  }

  if (violations.length > 0) {
    process.stderr.write(`SDK runtime entrypoint check failed:\n${violations.map((item) => `  - ${item}`).join('\n')}\n`);
    process.exitCode = 1;
    return;
  }

  if (write) {
    process.stdout.write('wrote SDK runtime entrypoint wrappers\n');
  } else {
    process.stdout.write('SDK runtime entrypoint wrappers are canonical\n');
  }
}

main().catch((error) => {
  process.stderr.write(`check-sdk-runtime-entrypoints failed: ${String(error)}\n`);
  process.exitCode = 1;
});
