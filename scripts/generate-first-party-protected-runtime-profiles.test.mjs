import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import YAML from 'yaml';
import {
  compileFirstPartyProtectedRuntimeProfiles,
  SOURCE_RELATIVE,
  RPC_SOURCE_RELATIVE,
  writeOrCheckCompiledProfiles,
} from './lib/first-party-protected-runtime-profile-compiler.mjs';

const repoRoot = path.resolve(import.meta.dirname, '..');
const sourceText = fs.readFileSync(path.join(repoRoot, SOURCE_RELATIVE), 'utf8');
const rpcSourceText = fs.readFileSync(path.join(repoRoot, RPC_SOURCE_RELATIVE), 'utf8');

function mutate(mutator) {
  const value = YAML.parse(sourceText);
  mutator(value);
  return YAML.stringify(value);
}

function compile(source = sourceText) {
  return compileFirstPartyProtectedRuntimeProfiles({ repoRoot, sourceText: source, rpcSourceText });
}

function rejectsMutation(mutator, pattern) {
  assert.throws(() => compile(mutate(mutator)), pattern);
}

test('compiles all profiles and freezes Avatar, Product Control, and ordinary parity', () => {
  const { model, outputs } = compile();
  assert.deepEqual(model.profiles.map((profile) => [profile.profileId, profile.methods.length]), [
    ['desktop_machine_product_v1', 64],
    ['desktop_account_product_v1', 49],
    ['bundled_avatar_v1', 31],
  ]);
  assert.equal(model.parity.avatar.fingerprint, '4bc4aa263abe992c343766af7d0943d8a1ef3131fb5447893917852af57b417e');
  assert.equal(model.parity.avatar.capabilityFingerprint, '39a009f27f1c9f7c8c54ee96b3404c64e554ae0a1fa93ed1a2f8d2a6322cc4ab');
  assert.equal(model.parity.productControl.fingerprint, '7fbaf4a067eab9d111bd4fc074c855db0cc7c56de37c5c84df0f3f389c329e14');
  assert.equal(model.parity.ordinary.fingerprint, 'b86770bcf80f89693a63a1b46e726d1ff3c8e1b251ffb05a9da5ac594e0efffb');
  assert.equal(outputs.size, 8);
});

test('rejects duplicate and wildcard methods', () => {
  rejectsMutation((value) => value.profiles[0].methods.push({ ...value.profiles[0].methods[0] }), /duplicate method/u);
  rejectsMutation((value) => { value.profiles[0].methods[0].method_id = '/nimi.runtime.v1.RuntimeLocalService/*'; }, /wildcard method id/u);
});

test('rejects unknown fields, RPCs, references, and kind mismatches', () => {
  rejectsMutation((value) => { value.profiles[0].unexpected = true; }, /unknown field/u);
  rejectsMutation((value) => { value.profiles[0].methods[0].method_id = '/nimi.runtime.v1.RuntimeLocalService/DoesNotExist'; }, /unknown RPC method/u);
  rejectsMutation((value) => { value.profiles[0].methods[0].intent_refs = ['missing_intent']; }, /unknown intent_ref/u);
  rejectsMutation((value) => { value.profiles[0].methods[0].kind = 'server_stream'; }, /RPC kind mismatch/u);
});

test('rejects missing intent, postcondition, negative-test, and Avatar capability closure', () => {
  rejectsMutation((value) => { value.profiles[0].methods[0].intent_refs = []; }, /intent_refs must be a non-empty/u);
  rejectsMutation((value) => { value.intents.product_control.owner_postcondition_refs = []; }, /owner_postcondition_refs must be a non-empty/u);
  rejectsMutation((value) => { value.profiles[0].negative_test_ref = 'missing'; }, /unknown negative_test_ref/u);
  rejectsMutation((value) => { delete value.profiles[2].methods[0].capability; }, /capability must be a non-empty/u);
});

test('rejects parity drift', () => {
  rejectsMutation((value) => { value.migration_parity_views.product_control_v1.expected_method_count = 20; }, /parity mismatch/u);
  rejectsMutation((value) => { value.migration_parity_views.ordinary_desktop_runtime_consumer_v1.methods.pop(); }, /parity mismatch/u);
  rejectsMutation((value) => { value.profiles[2].methods[0].capability = 'runtime.health.changed'; }, /parity mismatch/u);
});

test('detects compiler-owned orphan outputs', () => {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'nimi-profile-compiler-'));
  try {
    for (const [relative, content] of [[SOURCE_RELATIVE, sourceText], [RPC_SOURCE_RELATIVE, rpcSourceText]]) {
      const target = path.join(temporary, relative);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content);
    }
    writeOrCheckCompiledProfiles({ repoRoot: temporary, checkOnly: false });
    const orphan = path.join(temporary, 'runtime/internal/protectedlocal/orphan_generated.go');
    fs.writeFileSync(orphan, '// Code generated by scripts/generate-first-party-protected-runtime-profiles.mjs; DO NOT EDIT.\n');
    assert.throws(
      () => writeOrCheckCompiledProfiles({ repoRoot: temporary, checkOnly: true }),
      /orphan:runtime\/internal\/protectedlocal\/orphan_generated\.go/u,
    );
  } finally {
    fs.rmSync(temporary, { recursive: true, force: true });
  }
});
