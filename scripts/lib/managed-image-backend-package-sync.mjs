import fs from 'node:fs';
import path from 'node:path';

export const SOURCE_RELATIVE = 'config/runtime-managed-image-backend-packages.yaml';
export const OUTPUT_RELATIVE = 'runtime/internal/engine/generated/managed-image-backend-packages.yaml';

export function renderManagedImageBackendPackages(sourceText) {
  const normalized = String(sourceText).replace(/\r\n/gu, '\n').replace(/\s*$/u, '');
  return `# Code generated by scripts/generate-managed-image-backend-packages.mjs. DO NOT EDIT.\n${normalized}\n`;
}

export function assertManagedImageBackendPackageProjection(sourceText, outputText) {
  const expected = renderManagedImageBackendPackages(sourceText);
  if (String(outputText) !== expected) {
    throw new Error('managed image backend package generated projection is out of date');
  }
}

export function writeOrCheckManagedImageBackendPackages({ repoRoot, checkOnly }) {
  const sourcePath = path.join(repoRoot, SOURCE_RELATIVE);
  const outputPath = path.join(repoRoot, OUTPUT_RELATIVE);
  const sourceText = fs.readFileSync(sourcePath, 'utf8');
  const output = renderManagedImageBackendPackages(sourceText);
  if (checkOnly) {
    assertManagedImageBackendPackageProjection(sourceText, fs.readFileSync(outputPath, 'utf8'));
    return;
  }
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, output);
}
