#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { parse as parseYaml } from 'yaml';

const repoRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
const manifestFile = resolve(repoRoot, 'sdks/typescript/core-generated/runtime-core.manifest.json');
const authPostureIndexFile = resolve(
  repoRoot,
  'config/spec-frozen/runtime/tables/runtime-rpc-auth-posture.yaml',
);
const outputFiles = [
  resolve(repoRoot, 'kit/shell/tauri/src/runtime_bridge/generated/method_ids.rs'),
];

const STATIC_DENIED_METHOD_IDS = Object.freeze([
  '/nimi.runtime.v1.RuntimeWorkflowService/SubmitWorkflow',
  '/nimi.runtime.v1.RuntimeWorkflowService/GetWorkflow',
  '/nimi.runtime.v1.RuntimeWorkflowService/CancelWorkflow',
  '/nimi.runtime.v1.RuntimeWorkflowService/SubscribeWorkflowEvents',
  '/nimi.runtime.v1.RuntimeModelService/ListModels',
  '/nimi.runtime.v1.RuntimeModelService/PullModel',
  '/nimi.runtime.v1.RuntimeModelService/RemoveModel',
  '/nimi.runtime.v1.RuntimeModelService/CheckModelHealth',
  '/nimi.runtime.v1.RuntimeLocalService/ResolveLocalStateReconciliation',
  '/nimi.runtime.v1.RuntimeLocalService/ExecuteLocalStateCutover',
]);

const GENERIC_BRIDGE_DENIED_POSTURES = Object.freeze(new Set([
  'protected_origin_required',
  'deny_all_tombstone',
  'blocked_pending_authority',
  'unavailable_by_authority',
]));

function readManifest() {
  const manifest = JSON.parse(readFileSync(manifestFile, 'utf8'));
  if (!Array.isArray(manifest.method_ids)) {
    throw new Error('runtime core manifest missing method_ids array');
  }
  if (!Array.isArray(manifest.codec_maps)) {
    throw new Error('runtime core manifest missing codec_maps array');
  }
  return manifest;
}

function readPostureDeniedMethodIds(methodIdSet) {
  const index = parseYaml(readFileSync(authPostureIndexFile, 'utf8'));
  const denied = new Set();
  const seen = new Set();
  for (const shard of index?.method_shards ?? []) {
    const shardFile = resolve(dirname(authPostureIndexFile), 'runtime-rpc-auth-posture', basename(String(shard.path || '')));
    const document = parseYaml(readFileSync(shardFile, 'utf8'));
    const methods = document?.methods ?? [];
    if (Number(shard.method_count) !== methods.length) {
      throw new Error(`runtime bridge auth-posture shard count mismatch: ${shardFile}`);
    }
    for (const row of methods) {
      const methodId = String(row?.method_id || '').trim();
      const posture = String(row?.posture || '').trim();
      if (!methodIdSet.has(methodId)) {
        throw new Error(`runtime bridge auth-posture method missing from manifest: ${methodId}`);
      }
      if (seen.has(methodId)) {
        throw new Error(`runtime bridge auth-posture method duplicated: ${methodId}`);
      }
      seen.add(methodId);
      if (GENERIC_BRIDGE_DENIED_POSTURES.has(posture)) denied.add(methodId);
    }
  }
  return denied;
}

function uniqueSorted(values) {
  return Array.from(new Set(values)).sort();
}

function toRustConst(name, values) {
  const lines = values.map((value) => `    "${value}",`);
  return `pub const ${name}: &[&str] = &[\n${lines.join('\n')}\n];`;
}

function buildRustSource(allowlistedMethods, streamMethods) {
  return `// @generated by scripts/generate-runtime-bridge-methods.mjs
// DO NOT EDIT MANUALLY.

${toRustConst('RUNTIME_BRIDGE_ALLOWLISTED_METHODS', allowlistedMethods)}

${toRustConst('RUNTIME_BRIDGE_STREAM_METHODS', streamMethods)}

pub fn is_allowlisted_method(method_id: &str) -> bool {
    RUNTIME_BRIDGE_ALLOWLISTED_METHODS.contains(&method_id)
}

pub fn is_stream_method(method_id: &str) -> bool {
    RUNTIME_BRIDGE_STREAM_METHODS.contains(&method_id)
}
`;
}

function main() {
  const checkMode = process.argv.includes('--check');
  const manifest = readManifest();
  const methodIds = manifest.method_ids.map((methodId) => String(methodId));
  const methodIdSet = new Set(methodIds);
  const deniedMethods = readPostureDeniedMethodIds(methodIdSet);
  for (const methodId of STATIC_DENIED_METHOD_IDS) deniedMethods.add(methodId);
  const missingDeniedMethods = STATIC_DENIED_METHOD_IDS.filter((methodId) => !methodIdSet.has(methodId));
  if (missingDeniedMethods.length > 0) {
    throw new Error(`runtime bridge denied methods missing from manifest: ${missingDeniedMethods.join(', ')}`);
  }
  const allowlistedMethods = uniqueSorted(
    methodIds.filter((method) => !deniedMethods.has(method)),
  );

  const streamMethods = uniqueSorted(
    manifest.codec_maps
      .filter((entry) => entry?.kind === 'server_stream')
      .map((entry) => String(entry.method_id || ''))
      .filter((methodId) => methodId && !deniedMethods.has(methodId)),
  );

  const unknownStreams = streamMethods.filter(
    (method) => !allowlistedMethods.includes(method),
  );
  if (unknownStreams.length > 0) {
    throw new Error(`stream methods not in allowlist: ${unknownStreams.join(', ')}`);
  }

  const rendered = buildRustSource(allowlistedMethods, streamMethods);
  if (checkMode) {
    for (const outputFile of outputFiles) {
      let current = '';
      try {
        current = readFileSync(outputFile, 'utf8');
      } catch {
        process.stderr.write(
          `runtime bridge method file missing: ${outputFile}\n` +
          'run `pnpm generate:runtime-bridge-methods` to regenerate.\n',
        );
        process.exitCode = 1;
        return;
      }
      if (current !== rendered) {
        process.stderr.write(
          `runtime bridge method drift detected: ${outputFile}\n` +
          'run `pnpm generate:runtime-bridge-methods` to regenerate.\n',
        );
        process.exitCode = 1;
        return;
      }
    }
    process.stdout.write(`up-to-date ${outputFiles.join(', ')}\n`);
    return;
  }

  for (const outputFile of outputFiles) {
    writeFileSync(outputFile, rendered, 'utf8');
  }
  process.stdout.write(`generated ${outputFiles.join(', ')}\n`);
}

main();
