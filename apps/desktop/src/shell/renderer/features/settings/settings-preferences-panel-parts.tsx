import type { ReactNode } from 'react';
import { Toggle as KitToggle } from '@nimiplatform/kit/ui';

type SettingRowProps = {
  icon?: ReactNode;
  title: string;
  description: string;
  checked: boolean;
  onChange: (value: boolean) => void;
};

function ToggleSwitch({ checked, onChange }: { checked: boolean; onChange: (value: boolean) => void }) {
  return <KitToggle checked={checked} onChange={onChange} />;
}

export function SettingRow({ icon, title, description, checked, onChange }: SettingRowProps) {
  return (
    <div className="flex items-center justify-between px-5 py-4 transition-colors hover:bg-gray-50/50">
      <div className="flex items-center gap-4">
        {icon ? (
          <div className={`flex h-10 w-10 items-center justify-center rounded-xl ${checked ? 'bg-mint-100 text-mint-600' : 'bg-gray-100 text-gray-500'}`}>
            {icon}
          </div>
        ) : null}
        <div>
          <p className="text-sm font-medium text-gray-900">{title}</p>
          <p className="text-xs text-gray-500">{description}</p>
        </div>
      </div>
      <ToggleSwitch checked={checked} onChange={onChange} />
    </div>
  );
}

